function createEntry(content, dialogId) {
  const wrapper = document.createElement('div');
  wrapper.className = 'concept-layer-entry';
  wrapper.innerHTML = `
    <button class="concept-layer-entry__button" type="button" aria-haspopup="dialog" aria-controls="${dialogId}" aria-label="Kontext und Konzept öffnen">
      Konzept
    </button>
  `;
  return wrapper;
}

function createDialog(content, dialogId) {
  const root = document.createElement('div');
  root.className = 'concept-layer-root';
  root.id = dialogId;
  root.hidden = true;
  root.innerHTML = `
    <aside class="concept-layer-panel" role="dialog" aria-modal="false" aria-labelledby="${dialogId}-title">
      <div class="concept-layer-topbar">
        <div>
          <div class="concept-layer-kicker">Kontext</div>
          <h2 class="concept-layer-title" id="${dialogId}-title">${content.title}</h2>
        </div>
        <button class="concept-layer-close" type="button">Schließen</button>
      </div>
      <p class="concept-layer-intro">${content.intro}</p>
      <div class="concept-layer-sections">
        ${content.sections
          .map(
            (section) => `
              <section class="concept-layer-section">
                <span class="concept-layer-section__label">${section.label}</span>
                <p>${section.body}</p>
              </section>
            `,
          )
          .join('')}
      </div>
    </aside>
  `;
  return root;
}

export function initConceptLayer(pageKey, options = {}) {
  const content = conceptLayerContent[pageKey];
  if (!content) return;

  injectStyles();

  const dialogId = `concept-layer-${pageKey}`;
  const entryId = `${dialogId}-entry`;
  const mountTarget = options.mountSelector
    ? document.querySelector(options.mountSelector)
    : document.body;

  if (!mountTarget) return;
  if (document.getElementById(dialogId) || document.getElementById(entryId)) return;

  const entry = createEntry(content, dialogId);
  entry.id = entryId;
  const dialog = createDialog(content, dialogId);
  const trigger = entry.querySelector('.concept-layer-entry__button');
  const closeButton = dialog.querySelector('.concept-layer-close');
  const panel = dialog.querySelector('.concept-layer-panel');
  let lastFocusedElement = null;

  function openDialog() {
    lastFocusedElement = document.activeElement;
    dialog.hidden = false;
    requestAnimationFrame(() => {
      dialog.classList.add('is-visible');
    });
    closeButton?.focus();
  }

  function closeDialog() {
    dialog.classList.remove('is-visible');
    window.setTimeout(() => {
      if (!dialog.classList.contains('is-visible')) {
        dialog.hidden = true;
      }
    }, 220);
    if (lastFocusedElement instanceof HTMLElement) {
      lastFocusedElement.focus();
    } else {
      trigger?.focus();
    }
  }

  trigger?.addEventListener('click', () => {
    if (dialog.hidden) {
      openDialog();
      return;
    }

    closeDialog();
  });
  closeButton?.addEventListener('click', closeDialog);

  document.addEventListener('pointerdown', (event) => {
    if (dialog.hidden) return;

    const target = event.target;
    if (!(target instanceof Node)) return;
    if (panel?.contains(target) || trigger?.contains(target)) return;

    closeDialog();
  });

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && !dialog.hidden) {
      closeDialog();
    }
  });

  document.body.append(entry);
  document.body.append(dialog);

  if (panel) {
    panel.addEventListener('click', (event) => event.stopPropagation());
  }
}
